"""Rebuilds pcstation_launcher_ui.py (the page embedded in the .exe) from the sources in ui_src/.
Run:  python pc/build_ui.py   after editing anything in pc/ui_src/"""
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "ui_src")
read = lambda n: open(os.path.join(src, n), encoding="utf-8").read()
html = (read("index.html").replace("/*__CSS__*/", read("style.css")).replace("/*__SFX__*/", read("sfx.js"))
        .replace("/*__APP__*/", read("app.js")).replace("<!--__GAMEPAD__-->", read("gamepad.svg.html")))
assert '"""' not in html
with open(os.path.join(here, "pcstation_launcher_ui.py"), "w", encoding="utf-8") as f:
    f.write('"""The launcher page, embedded so it is bundled into the single .exe. Generated by build_ui.py from ui_src/."""\n\nHTML = r"""' + html + '"""\n')
print("built pcstation_launcher_ui.py", len(html), "bytes")
